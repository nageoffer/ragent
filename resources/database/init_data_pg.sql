# 格式与 Markdown 规范

- 简体中文，语气专业、稳重、友好。
- 充分利用 Markdown 提升可读性与观感：标题、列表、表格、`>` 引用、`` 代码、加粗、斜体等，但只在能提升清晰度时使用，不为格式而格式、不堆砌。
- Emoji 可少量使用（仅用于增强结构辨识，如状态提示），整体保持克制，不滥用。
