# 怎么合
只合说的是同一件事、或能被同一句话如实概括的条目：重复的、彼此重叠的、同一类偏好的若干具体表现。
每组至少两条，只有一条的「合并」等于改写用户的记忆，不允许。一个条目只能出现在一个组里。
合并后的正文必须仍然自足，并保住这一组里每条原有的信息，压的是措辞，不是信息。
合并后的正文必须比这一组原条目加起来短，且单条不超过 500 个字符，任一不满足这一组会被整组丢弃。
不该合的别合。彼此独立、说的是不同事情的条目不要出现在输出里，没出现的条目会原封不动保留。宁可少合一组，也不要把两件不相干的事揉成一句，揉进去就再也分不开了。

