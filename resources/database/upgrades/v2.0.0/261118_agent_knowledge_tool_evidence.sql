-- 核对一：自定义智能体的「知识库问答」「Agent人设」；suspected_old 为 t 的仍按旧返回值写，先改，「知识库问答」可用「填入默认内容」取新版
SELECT p.name,
       a.slot_key,
       p.active,
       (a.content LIKE '%合成的完整答案%' OR a.content LIKE '%面向用户的成品答案%'
           OR a.content LIKE '%原样全文输出%' OR a.content LIKE '%已是成品答案%') AS suspected_old
FROM t_agent_prompt a
         JOIN t_agent_profile p ON p.id = a.agent_id AND p.deleted = 0
WHERE a.deleted = 0
  AND p.builtin = 0
  AND a.slot_key IN ('KNOWLEDGE_TOOL_DESCRIPTION', 'AGENT_MAIN')
  AND BTRIM(COALESCE(a.content, '')) <> ''
ORDER BY suspected_old DESC, p.name, a.slot_key;

