-- 进程读的是 Redis 缓存：删 key 后发一次请求，redis-cli GET ragent:agent:resolved-prompts:v2 里应能找到同一句
SELECT p.name                                                                                       AS active_agent,
       LEFT(SPLIT_PART(COALESCE(NULLIF(BTRIM(own.content), ''), builtin.content), E'\n', 1), 60) AS effective_first_line
FROM t_agent_profile p
         LEFT JOIN t_agent_prompt own
                   ON own.agent_id = p.id AND own.slot_key = 'KNOWLEDGE_TOOL_DESCRIPTION' AND own.deleted = 0
         LEFT JOIN t_agent_prompt builtin
                   ON builtin.agent_id = '2001523723396309001' AND builtin.slot_key = 'KNOWLEDGE_TOOL_DESCRIPTION'
                       AND builtin.deleted = 0
WHERE p.active = 1
  AND p.deleted = 0;
