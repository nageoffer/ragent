UPDATE t_agent_skill
SET content     = $prompt$## 什么时候用
用户要取消订单或改收货信息时，按本手册办。
只问「多久不付款会自动取消」「发货后还能不能改地址」这类规则，走知识库，不用本手册。

## 办事步骤
1. 先用 query_order 确认是哪一单，拿到当前状态。用户只说「刚才那单」时，列最近几笔让他确认
2. 按状态分流，四个状态四条路：
   - 待支付：能取消，也能改收货信息
   - 已支付待发货：能取消（原路退款），也能改收货信息
   - 已发货：两件都办不了。取消改成建议拒收，拒收后自动退款；改地址改成建议联系快递改派
   - 已签收或已取消：两件都办不了。已签收要退就走售后申请，已取消不用再取消一次
3. 取消前先把这单会一起发生的事讲给用户：用掉的券退回、已支付的原路退款、库存回补。这段话写在发起 cancel_order 的那条回复正文里、放在调用之前，不能等提交结果出来再补；用户一上来就明确要取消，也照样先讲
4. 改地址前把要改的项和改成什么当场列出来，让用户确认无误再提交
5. 用 cancel_order 或 change_address 提交，把结果如实回给用户

## 这几项怎么填
- 订单号取自 query_order 的返回值，不要凭对话内容拼
- change_address 的收货人、手机号、地址三项，用户没说要改的就不要传：传了就会覆盖原值
- 订单查询返回的手机号是打码的，不要拿打码值当原值回填进去
- 地址要完整到门牌号，用户只说「换到公司」这类不完整信息时问清楚再提交

## 系统的硬约束
- 能不能取消、能不能改，由工具按库里的实时状态判定，不要拿几轮之前查到的状态下结论
- 只有待支付和已支付待发货能改收货信息，已发货之后改不动
- 手机号格式不合法、地址太短会被直接回绝，与其被打回不如先问清楚
- 提交时若返回「状态刚发生变化」，说明这单在两次操作之间被改了，重新查一次订单再决定，不要反复重试
