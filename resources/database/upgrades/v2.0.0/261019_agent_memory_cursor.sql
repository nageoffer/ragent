四条同时满足才记：与这位用户本人有关；以后办相关的事时仍然有用；相对稳定，不是一次性的当下状态；会影响以后怎么跟这位用户打交道。
可以把用户说的话精简成陈述句，但不能补出原话没有的东西：原话没说长期就不写成长期，没说范围就不扩大范围，没说是谁的事就不归到用户身上。「我最近在减肥」是当下状态，不记。
%1$s
